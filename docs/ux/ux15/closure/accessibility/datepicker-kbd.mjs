import { webkit, chromium } from 'playwright';
import { personaContext } from './auth.mjs';
const BASE = 'http://127.0.0.1:8090';
const exe = 'process.env.WEBKIT_EXE';
const engine = process.argv[2] ?? 'webkit';
const b = engine === 'webkit' ? await webkit.launch({ executablePath: exe }) : await chromium.launch();
const { page: p } = await personaContext(b, BASE, 'kavya.menon@demo.local', { viewport: { width: 1440, height: 1000 } });
await p.goto(BASE + '/admin/departments/create', { waitUntil: 'networkidle' }); await p.waitForTimeout(800);
const field = p.locator('.fi-fo-date-time-picker').first();
const input = field.locator('.fi-fo-date-time-picker-display-text-input');
const panel = field.locator('.fi-fo-date-time-picker-panel');
const r = { engine, tag: await field.locator('.fi-fo-date-time-picker-trigger').evaluate((e) => e.tagName) };
await input.focus(); r.focused = await input.evaluate((e) => document.activeElement === e);
await p.keyboard.press('Enter'); await p.waitForTimeout(400); r.enterOpens = await panel.isVisible();
await p.keyboard.press('ArrowRight'); await p.keyboard.press('Enter'); await p.waitForTimeout(400); r.value = await input.inputValue(); r.closedAfterPick = !(await panel.isVisible());
await p.keyboard.press('Escape'); await p.waitForTimeout(300);
await input.click(); await p.waitForTimeout(300); r.clickOpens = await panel.isVisible();
await p.keyboard.press('Escape'); await p.waitForTimeout(400); r.escapeCloses = !(await panel.isVisible());
console.log(JSON.stringify(r));
await b.close();
