import { chromium } from '@playwright/test';
const [,, email, path, out, w, h] = process.argv;
const b = await chromium.launch();
const login = await b.newContext(); const lp = await login.newPage();
await lp.goto('http://127.0.0.1:8093/admin/login'); await lp.fill('input[type=email]', email); await lp.fill('input[type=password]', 'password');
await Promise.all([lp.waitForURL(/\/admin$/, { timeout: 120000 }), lp.click('button[type=submit]')]);
const st = await login.storageState(); await login.close();
const ctx = await b.newContext({ viewport: { width: +w, height: +h }, hasTouch: +w < 1024, isMobile: +w < 1024, storageState: st, reducedMotion: 'reduce' });
const p = await ctx.newPage(); await p.goto('http://127.0.0.1:8093' + path, { waitUntil: 'networkidle' }); await p.evaluate(() => document.fonts.ready);
await p.screenshot({ path: out }); await b.close();
