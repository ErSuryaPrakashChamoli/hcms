"""Writes database/data/compliance/reports/in.php from the specs (catalogue revision 2026-10-27b)."""
import sys, os, importlib
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from central_spec import C
from se_spec import S, B
from ptlwf_spec import PT, LWF
from thresholds_spec import T
from sources_spec import SE
from se2_spec import SE2

NONFACTORY = ['registered_office', 'office', 'branch', 'warehouse', 'shop', 'site', 'other']
ORDER = ['AN','AP','AR','AS','BR','CH','CG','DH','DL','GA','GJ','HR','HP','JK','JH','KA','KL','LA','LD','MP','MH','MN','ML','MZ','NL','OD','PY','PB','RJ','SK','TN','TG','TR','UP','UK','WB']
CONF = {'primary': 'OFFICIAL_PRIMARY_SOURCE_VERIFIED', 'official': 'OFFICIAL_SOURCE_PARTIALLY_VERIFIED', 'secondary': 'SECONDARY_SOURCE_ONLY', 'unverified': 'UNVERIFIED', 'conflicting': 'CONFLICTING_SOURCES', 'review': 'LEGAL_REVIEW_REQUIRED'}
V = '2026-10-26'

def q(v, ind=0):
    if v is None: return 'null'
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, int): return str(v)
    if isinstance(v, float): return repr(v)
    if isinstance(v, (list, tuple)):
        return '[' + ', '.join(q(x) for x in v) + ']'
    if isinstance(v, dict):
        return '[' + ', '.join(f"{q(k)} => {q(x)}" for k, x in v.items()) + ']'
    return "'" + str(v).replace('\\', '\\\\').replace("'", "\\'") + "'"

def entry(key, d, pad):
    items = [(k, v) for k, v in d.items() if v is not None and v != [] and v != '' and v != {}]
    return f"{pad}{q(key)} => [" + ', '.join(f"'{k}' => {q(v)}" for k, v in items) + "],\n"

def conf(c):
    return CONF.get(c, c)

out = []
out.append("""<?php

/*
| Compliance report catalogue (India), revision 2026-10-27b: the registers, challans, returns and statements an
| employer's HR and payroll team maintains or files, central (all-India) and per state. Read by
| App\\Domain\\ComplianceReports\\Support\\ReportCatalogue. Generated from the research specs; edit with care and keep the
| sourcing honest — the catalogue never upgrades a confidence label by itself.
|
| An entry with a `builder` is generated by PeopleOS (peopleos.compliance.report_builders); one without is listed as a
| checklist item kept on the authority's portal, in physical registers or in other systems.
|
| frequency   monthly | quarterly | half_yearly | yearly | register (kept continuously) | event (checklist only)
| basis       the year a quarter / half-year / year follows when it differs from the pack's (financial | calendar)
| scope       establishment | state | legal_entity | company
| due         months after the period's last month and the day of that month ('end' = its last day); end_month
|             overrides the rule for periods ending in that month
| requires    statute that must apply to the establishment (EPF, ESI, PT, LWF, TDS) per its statutory profile
| sphere      central | state: the entry applies only where that government is the appropriate government
| code        wages (default: Code on Wages and OSH Code) | ss (Code on Social Security): which appropriate government
|             field of the establishment the sphere and variants read
| variants    form and legal basis by appropriate government (sphere: central | state | unknown), states and dates
|             (from / to, compared with the period's end); the first match wins
| thresholds  dated applicability windows: min, measure (employed_any_day | employed_period_end | employed_during),
|             basis, confidence
| effective_from / effective_to   when the obligation itself is in force
| output      register | working_sheet | statement | check | checklist — none of them is a filing
| filing      where the employer files or pays, outside PeopleOS
| obligation  statutory | internal_control
| confidence  OFFICIAL_PRIMARY_SOURCE_VERIFIED | OFFICIAL_SOURCE_PARTIALLY_VERIFIED | SECONDARY_SOURCE_ONLY |
|             CONFLICTING_SOURCES | LEGAL_REVIEW_REQUIRED | UNVERIFIED
| sources     [title, url] pairs; verified_on the date the sources were last checked; legal_review what remains open
|
| Statutory rates and ceilings are not here: they live in versioned compliance rules (database/data/compliance/in.php).
*/

return [
    'reviewed' => [
        'on' => '2026-10-27',
        'revision' => '2026-10-27b',
        'position' => 'The four Labour Codes are in force from 21 November 2025. Central rules under them were notified on 8 May 2026 (Wages (Central) Rules, 2026 G.S.R. 343(E); Industrial Relations G.S.R. 342(E); Social Security G.S.R. 344(E); OSH G.S.R. 345(E)) and apply where the Central Government is the appropriate government: registers in Forms I, IV and IX, the unified annual return in Form XVII. Where a state government is the appropriate government (most private shops, offices and factories), that state\\'s rules under the Codes apply once notified, and its earlier Acts and rules until then. PeopleOS asks for each establishment\\'s appropriate government instead of assuming it. State facts carry their own source confidence; many rest on secondary sources and need professional review.',
    ],

    'central' => [
""")
for key, d in C.items():
    d = dict(d)
    out.append(entry(key, d, '        '))
out.append("    ],\n\n    'states' => [\n")

for code in ORDER:
    s = S[code]
    act = s['act']
    src = SE2.get(code, []) + [[f"{s['name']} — shops and establishments source", u] for u in SE.get(code, []) if u not in [x[1] for x in SE2.get(code, [])]]
    thresholds = T.get(code)
    reports = []
    for (key, b, title, form, rule, cf) in s['registers']:
        builder, freq = B[b]
        reports.append((key, {'title': title, 'category': 'register', 'frequency': freq, 'scope': 'establishment', 'builder': builder,
            'source': 'attendance' if b in ('MR', 'OT') else ('leave' if b == 'LR' else ('people' if b == 'ER' else 'payroll')),
            'output': 'register', 'establishment_types': NONFACTORY, 'thresholds': thresholds, 'form': form, 'legal_basis': f'{act}, {rule}',
            'due_text': 'Kept current; produced on inspection', 'confidence': conf(cf), 'sources': src, 'verified_on': V,
            'legal_review': 'Shops and establishments forms are from research summaries; confirm the current form with the state rules.' if conf(cf) != 'OFFICIAL_PRIMARY_SOURCE_VERIFIED'
                else 'The state rules prescribe this form (official text read); the workbook uses the PeopleOS register layout with its particulars: check it against the printed form before relying on it.'}))
    for r in s['returns']:
        key, title, form, rule, due, due_text, cf = r[:7]
        freq = r[7] if len(r) > 7 else 'yearly'
        mn = r[8] if len(r) > 8 else None
        basis = r[9] if len(r) > 9 else 'calendar'
        th = [{'min': mn, 'measure': 'employed_period_end', 'basis': f'{act}, {rule}', 'confidence': conf(cf)}] if mn else thresholds
        reports.append((key, {'title': title, 'category': 'annual' if freq == 'yearly' else 'return', 'frequency': freq, 'basis': basis, 'scope': 'establishment',
            'builder': 'return_working_sheet', 'source': 'attendance', 'output': 'working_sheet', 'filing': 'State labour department portal', 'establishment_types': NONFACTORY,
            'thresholds': th, 'form': form, 'legal_basis': f'{act}, {rule}', 'due': due, 'due_text': due_text, 'confidence': conf(cf), 'sources': src, 'verified_on': V,
            'legal_review': 'Return form and due date from research summaries; confirm with the state rules.' if conf(cf) != 'OFFICIAL_PRIMARY_SOURCE_VERIFIED'
                else 'The return and its due date are from the official text; the working sheet is a PeopleOS layout, not the portal form.'}))
    for c in s['checklist']:
        key, title, form, rule, freq, basis, due, due_text, cf = c
        reports.append((key, {'title': title, 'category': 'checklist', 'frequency': freq, 'basis': basis, 'output': 'checklist', 'form': form,
            'legal_basis': f'{act}, {rule}', 'due': due, 'due_text': due_text, 'confidence': conf(cf), 'sources': src, 'verified_on': V}))
    pt = PT.get(code)
    if pt and pt.get('levied'):
        reports.append(('pt_statement', {'title': 'Professional tax statement', 'category': 'return', 'frequency': pt['frequency'], 'basis': pt.get('basis'),
            'scope': 'state', 'builder': 'pt_statement', 'output': 'statement', 'filing': 'State professional tax portal (payment and return)', 'form': pt.get('form', ''),
            'legal_basis': pt['act'], 'due': pt.get('due'), 'due_text': pt.get('due_text', ''), 'effective_from': pt.get('effective_from'), 'effective_to': pt.get('effective_to'),
            'confidence': conf(pt.get('confidence', 'secondary')), 'sources': pt.get('sources', []), 'verified_on': pt.get('verified_on', V), 'notes': pt.get('notes', []),
            'legal_review': pt.get('legal_review')}))
    lwf = LWF.get(code)
    if lwf and lwf.get('applies'):
        reports.append(('lwf_statement', {'title': 'Labour welfare fund statement', 'category': 'challan', 'frequency': lwf['frequency'], 'basis': lwf.get('basis'),
            'scope': 'state', 'builder': 'lwf_statement', 'output': 'statement', 'filing': 'State labour welfare board', 'form': lwf.get('form', ''),
            'legal_basis': lwf['act'], 'due': lwf.get('due'), 'due_text': lwf.get('due_text', ''), 'effective_from': lwf.get('effective_from'), 'effective_to': lwf.get('effective_to'),
            'confidence': conf(lwf.get('confidence', 'secondary')), 'sources': lwf.get('sources', []), 'verified_on': lwf.get('verified_on', V), 'notes': lwf.get('notes', []),
            'legal_review': lwf.get('legal_review')}))

    out.append(f"        '{code}' => [\n")
    out.append(f"            'name' => {q(s['name'])},\n")
    out.append(f"            'shops' => {q({'act': act, 'registers': s['summary_registers'], 'returns': s['summary_returns'], 'note': s['note']})},\n")
    if pt:
        summ = {'levied': pt.get('levied'), 'act': pt.get('act'), 'frequency': pt.get('frequency_text'), 'due': pt.get('due_text'), 'form': pt.get('form'),
                'confidence': conf(pt.get('confidence', '')) if pt.get('confidence') else None, 'note': pt.get('note')}
        out.append(f"            'pt' => {q({k: v for k, v in summ.items() if v is not None})},\n")
    if lwf:
        summ = {'applies': lwf.get('applies'), 'act': lwf.get('act'), 'employee': lwf.get('employee'), 'employer': lwf.get('employer'), 'frequency': lwf.get('frequency_text'),
                'due': lwf.get('due_text'), 'form': lwf.get('form'), 'confidence': conf(lwf.get('confidence', '')) if lwf.get('confidence') else None, 'note': lwf.get('note')}
        out.append(f"            'lwf' => {q({k: v for k, v in summ.items() if v is not None})},\n")
    out.append("            'reports' => [\n")
    for key, r in reports:
        out.append(entry(key, r, '                '))
    out.append("            ],\n        ],\n")
out.append("    ],\n];\n")
open(sys.argv[1], 'w').write(''.join(out))
