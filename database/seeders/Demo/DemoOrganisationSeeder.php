<?php

namespace Database\Seeders\Demo;

use App\Domain\Identity\Models\User;
use Database\Seeders\ProductionSeeder;
use Filament\Facades\Filament;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Str;
use RuntimeException;

/**
 * A complete, fictional demo organisation for showing PeopleOS working, on any server, production included:
 *
 *   php artisan db:seed --class="Database\Seeders\Demo\DemoOrganisationSeeder" --force
 *
 * It is never part of `db:seed` (DatabaseSeeder seeds only the baseline in production); running this class is the
 * decision. It builds one tenant, "Demo Group" at the address "demo", and fills every module through the domain services:
 *
 * 1. ProductionSeeder: the baseline (permissions, statutory packs) the demo needs, as on every deploy.
 * 2. DemoTenantSeeder: the tenant, two companies, the organisation tree, policies, workflows, onboarding, shifts, holidays,
 *    leave, salaries and a payroll run, performance, learning, assets, service desk, knowledge, announcements, an exit.
 * 3. DemoPeopleSeeder: two dozen people, one sign-in per experience lens, and live requests, moves and signals.
 * 4. DemoActivitySeeder: recent history: attendance, past leave, birthdays, next year's holidays, expenses, recognition.
 * 5. DemoNotificationsSeeder: in-app notifications for the personas.
 *
 * Safe to run again on every deploy: nothing is duplicated, and records people changed in the demo stay as they are.
 *
 * Sign-ins: every account is on the reserved, undeliverable demo.local domain (no e-mail leaves for them on production:
 * SuppressUndeliverableMail) and shares one password: PEOPLEOS_DEMO_PASSWORD (at least 12 characters), or, when that is
 * unset, a new one generated and printed by each run. Each run sets every demo.local account to that password. The
 * platform operator is never a demo account: operators come from ProductionSeeder (PEOPLEOS_BOOTSTRAP_OPERATOR_EMAIL).
 *
 * On production the readiness check keeps reporting the demo.local accounts (FAIL "No demo or test sign-in accounts")
 * for as long as the demo organisation can sign in: that line is true, and stays visible on purpose.
 */
class DemoOrganisationSeeder extends Seeder
{
    public const PASSWORD_REASON = 'Demo organisation: shared demo sign-in password (DemoOrganisationSeeder)';

    /** The personas to sign in as, by lens, for the summary printed at the end. */
    public const SIGN_INS = [
        'Tenant super admin (everything)' => DemoOrganisation::ADMIN_EMAIL,
        'HR admin (Kavya Menon)' => 'kavya.menon@demo.local',
        'HR business partner (Neha Kapoor)' => 'neha.kapoor@demo.local',
        'Payroll lead (Arjun Bose)' => 'arjun.bose@demo.local',
        'Executive / CEO (Meera Iyer)' => 'meera.iyer@demo.local',
        'Manager (Amit Verma)' => 'amit.verma@demo.local',
        'Employee (Priya Nair)' => 'priya.nair@demo.local',
        'Employee (Rahul Sharma)' => 'rahul.sharma@demo.local',
    ];

    public function run(): void
    {
        DemoOrganisation::assertClaimable(DemoOrganisation::tenant());
        [$password, $generated] = $this->password();

        $this->call(ProductionSeeder::class);
        $this->call(DemoTenantSeeder::class, false, ['password' => $password, 'policiesFrom' => DemoOrganisation::POLICIES_FROM]);
        $this->call(DemoPeopleSeeder::class, false, ['password' => $password]);
        $this->call(DemoActivitySeeder::class);
        $this->call(DemoNotificationsSeeder::class);
        $changed = $this->applyPassword($password);

        $this->summary($password, $generated, $changed);
    }

    /** @return array{0: string, 1: bool} the password and whether it was generated by this run */
    private function password(): array
    {
        $configured = (string) config('peopleos.demo.password', '');
        if ($configured === '') {
            return [Str::password(16, symbols: false), true];
        }
        if (mb_strlen($configured) < DemoOrganisation::MIN_PASSWORD_LENGTH) {
            throw new RuntimeException('PEOPLEOS_DEMO_PASSWORD must be at least '.DemoOrganisation::MIN_PASSWORD_LENGTH.' characters.');
        }

        return [$configured, false];
    }

    /** Every demo.local account of the demo tenant gets the password (a changed PEOPLEOS_DEMO_PASSWORD rotates them all). */
    private function applyPassword(string $password): int
    {
        $tenant = DemoOrganisation::tenant() ?? throw new RuntimeException('The demo organisation was not created.');
        $changed = 0;
        User::query()->where('tenant_id', $tenant->id)->where('is_platform_admin', false)->where('email', 'like', '%@demo.local')
            ->orderBy('id')->each(function (User $user) use ($password, &$changed) {
                if (Hash::check($password, $user->password)) {
                    return;
                }
                $user->forceFill(['password' => $password])->withAuditReason(self::PASSWORD_REASON)->save();
                $changed++;
            });

        return $changed;
    }

    private function summary(string $password, bool $generated, int $changed): void
    {
        if ($this->command === null) {
            return;
        }
        $this->command->newLine();
        $this->command->info('Demo organisation "'.DemoOrganisation::NAME.'" is ready. Sign in at '.rescue(fn () => Filament::getPanel('admin')->getLoginUrl(), url('/admin/login'), false));
        $this->command->table(['Sign in as', 'E-mail'], collect(self::SIGN_INS)->map(fn ($email, $lens) => [$lens, $email])->values()->all());
        if ($generated) {
            $this->command->warn("Password for every demo account (generated by this run, shown once): {$password}");
            $this->command->line('  Set PEOPLEOS_DEMO_PASSWORD (12+ characters) in .env to keep one password across runs.');
        } else {
            $this->command->line('  Password: the PEOPLEOS_DEMO_PASSWORD value'.($changed > 0 ? " (set on {$changed} account(s) this run)." : '.'));
        }
    }
}
